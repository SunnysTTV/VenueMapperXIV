    public static Version ParseVersion(string? version)
    {
        var s = (version ?? "").Trim().TrimStart('v', 'V');
        if (!Version.TryParse(s, out var v)) return new Version(0, 0, 0, 0);
        return new Version(v.Major, v.Minor, Math.Max(v.Build, 0), Math.Max(v.Revision, 0));
    }

    public static bool CrossedAny(IEnumerable<string> versions, string? fromVersion, string toVersion)
    {
        var from = ParseVersion(fromVersion);
        var to = ParseVersion(toVersion);
        return versions.Any(v => ParseVersion(v) is var pv && pv > from && pv <= to);
    }

